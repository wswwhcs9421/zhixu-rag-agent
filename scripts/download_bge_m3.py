"""Download a pinned official BAAI/bge-m3 dense model and verify every file.

Uses HTTP range requests with resumable parts, without changing global proxy settings.
Run from project root: .venv/Scripts/python.exe scripts/download_bge_m3.py
"""
from __future__ import annotations

import concurrent.futures
import hashlib
import json
import os
import sys
import time
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
DESTINATION = ROOT / "data/models/bge-m3"
REVISION = "5617a9f61b028005a4858fdac845db406aefb181"
BASE = "https://huggingface.co"
WEIGHTS_MIRROR = "https://hf-mirror.com"
FILES = {"config.json", "modules.json", "1_Pooling/config.json", "config_sentence_transformers.json",
         "sentence_bert_config.json", "sentencepiece.bpe.model", "special_tokens_map.json",
         "tokenizer.json", "tokenizer_config.json", "pytorch_model.bin"}
PART_SIZE = 32 * 1024 * 1024


def valid(path, info):
    if not path.is_file() or path.stat().st_size != info["size"]:
        return False
    if "lfs" in info:
        hasher = hashlib.sha256()
        expected = info["lfs"]["sha256"]
    else:
        hasher = hashlib.sha1()
        hasher.update(f"blob {info['size']}\0".encode())
        expected = info["blobId"]
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(4 * 1024 * 1024), b""):
            hasher.update(chunk)
    return hasher.hexdigest() == expected


def download_file(client, info):
    name = info["rfilename"]
    target = DESTINATION / name
    target.parent.mkdir(parents=True, exist_ok=True)
    if valid(target, info):
        print(f"Verified existing {name}", flush=True)
        return
    host = WEIGHTS_MIRROR if name == "pytorch_model.bin" else BASE
    url = f"{host}/BAAI/bge-m3/resolve/{REVISION}/{name}"
    if info["size"] < PART_SIZE:
        response = client.get(url)
        response.raise_for_status()
        temporary = target.with_name(target.name + ".partial")
        temporary.write_bytes(response.content)
    else:
        part_dir = DESTINATION / ".download" / name
        part_dir.mkdir(parents=True, exist_ok=True)
        ranges = [(begin, min(begin + PART_SIZE, info["size"]) - 1) for begin in range(0, info["size"], PART_SIZE)]

        def part(bounds):
            begin, end = bounds
            path = part_dir / f"{begin:012}.part"
            if path.is_file() and path.stat().st_size == end - begin + 1:
                return path
            for attempt in range(4):
                try:
                    # Unique query prevents proxies from reusing a different byte range.
                    with client.stream("GET", url, params={"download": "true", "rag_range": str(begin)},
                                       headers={"Range": f"bytes={begin}-{end}"}) as response:
                        response.raise_for_status()
                        expected = f"bytes {begin}-{end}/{info['size']}"
                        if response.status_code != 206 or response.headers.get("content-range") != expected:
                            raise ValueError(f"Server did not honor byte range {begin}-{end}")
                        with path.open("wb") as output:
                            for block in response.iter_bytes(1024 * 1024):
                                output.write(block)
                    if path.stat().st_size != end - begin + 1:
                        raise ValueError("Incomplete download part")
                    return path
                except (httpx.HTTPError, ValueError):
                    if attempt == 3:
                        raise
                    time.sleep(1 + attempt)

        completed = 0
        with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
            futures = [pool.submit(part, bounds) for bounds in ranges]
            for future in concurrent.futures.as_completed(futures):
                completed += future.result().stat().st_size
                print(f"{name}: {completed / info['size']:.1%} ({completed / 1024**2:.0f} MiB)", flush=True)
        temporary = target.with_name(target.name + ".partial")
        with temporary.open("wb") as output:
            for begin, end in ranges:
                with (part_dir / f"{begin:012}.part").open("rb") as stream:
                    for chunk in iter(lambda: stream.read(4 * 1024 * 1024), b""):
                        output.write(chunk)
    if not valid(temporary, info):
        raise ValueError(f"Official content hash does not match: {name}; keep parts for diagnosis")
    os.replace(temporary, target)
    if info["size"] >= PART_SIZE:
        # Only parts generated by this downloader, after full-file hash verification.
        for begin, end in ranges:
            (part_dir / f"{begin:012}.part").unlink()
        part_dir.rmdir()
    print(f"Downloaded and verified {name}", flush=True)


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    DESTINATION.mkdir(parents=True, exist_ok=True)
    with httpx.Client(timeout=httpx.Timeout(90, connect=20), follow_redirects=True) as client:
        response = client.get(f"{BASE}/api/models/BAAI/bge-m3/revision/{REVISION}", params={"blobs": "true"})
        response.raise_for_status()
        metadata = response.json()
        if metadata["sha"] != REVISION:
            raise ValueError("Unexpected upstream revision")
        selected = [info for info in metadata["siblings"] if info["rfilename"] in FILES]
        if {info["rfilename"] for info in selected} != FILES:
            raise ValueError("Upstream model file list changed")
        with httpx.Client(timeout=httpx.Timeout(90, connect=20), follow_redirects=True, trust_env=False) as mirror:
            for info in sorted(selected, key=lambda item: item["size"]):
                download_file(mirror if info["rfilename"] == "pytorch_model.bin" else client, info)
    (DESTINATION / "2_Normalize").mkdir(exist_ok=True)
    manifest = {"repository": "BAAI/bge-m3", "revision": REVISION, "source": BASE, "weights_mirror": WEIGHTS_MIRROR,
                "verified_files": selected, "downloaded_at_unix": time.time()}
    (DESTINATION / "download_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Model ready at {DESTINATION}", flush=True)


if __name__ == "__main__":
    main()
