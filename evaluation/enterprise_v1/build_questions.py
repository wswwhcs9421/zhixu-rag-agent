def build():
    sources = json.loads((ROOT / "sources.json").read_text(encoding="utf-8"))
    articles = json.loads((ROOT / "articles.json").read_text(encoding="utf-8"))
    source_map = {source["source_id"]: source for source in sources}
    article_map = {(article["source_id"], article["article"]): article for article in articles}
    reader = PdfReader(ROOT / "sources_raw/财政部_企业内部控制应用指引_官方原文.pdf")
    page_texts = [normalized(re.sub(r"(?m)^\s*\d+\s*$", "", page.extract_text() or "")) for page in reader.pages]
    cases = question_specs()
    for case in cases:
        evidence = []
        for index, (source_id, article_id, quote) in enumerate(case.pop("evidence_specs"), 1):
            article = article_map[source_id, article_id]
            quote = normalized(quote)
            if quote not in article["text"]:
                raise ValueError(f"{case['id']}: quote not present in {source_id} {article_id}: {quote}")
            if len(quote) > 120:
                raise ValueError(f"{case['id']}: quote longer than default overlap; split it into smaller evidence spans")
            source = source_map[source_id]
            corpus = (ROOT / source["path"]).read_text(encoding="utf-8")
            start = corpus.find(quote)
            if start < 0:
                raise ValueError(f"{case['id']}: quote missing from frozen corpus")
            # Locate the exact quote in the original, including quotes spanning two pages.
            page_ranges, combined = [], ""
            for page in article["pdf_pages"]:
                begin = len(combined)
                combined += page_texts[page - 1]
                page_ranges.append((begin, len(combined), page))
            quote_start = combined.find(quote)
            if quote_start < 0:
                raise ValueError(f"{case['id']}: quote missing from original PDF pages")
            quote_pages = [page for begin, end, page in page_ranges
                           if begin < quote_start + len(quote) and end > quote_start]
            evidence.append({"evidence_id": f"{case['id']}-E{index:02}", "source_id": source_id,
                             "filename": source["filename"], "article": article_id,
                             "quote": quote, "pdf_pages": quote_pages,
                             "url": source["url"] + f"#page={quote_pages[0]}",
                             "corpus_char_start": start, "corpus_char_end": start + len(quote)})
        case["evidence"] = evidence
        case["expected_source_ids"] = list(dict.fromkeys(e["source_id"] for e in evidence))
        case["evidence_logic"] = "all" if case["answerable"] else "not_applicable"
        case["question_origin"] = "根据真实公开制度原文人工编制的业务场景问题，非用户日志采样"
    if len(cases) != 44 or sum(case["answerable"] for case in cases) != 40:
        raise ValueError("Expected 40 answerable + 4 unanswerable questions")
    payload = "".join(json.dumps(case, ensure_ascii=False) + "\n" for case in cases)
    (ROOT / "questions.jsonl").write_text(payload, encoding="utf-8", newline="\n")
    meta = {"dataset_id": "enterprise_internal_control_v1", "snapshot_date": "2026-11-01",
            "source_count": len(sources), "question_count": len(cases),
            "answerable": 40, "unanswerable": 4,
            "types": dict(Counter(case["type"] for case in cases)),
            "questions_sha256": hashlib.sha256(payload.encode()).hexdigest(),
            "original_publication": "财政部企业内部控制应用指引，财会〔2010〕11号配套指引",
            "version_scope": "固定2010年原文的检索阅读理解评测，不代表某家企业现行制度或对现行法律效力的判断",
            "question_origin": "source-grounded manually authored realistic business questions; not production user logs",
            "upload_only": "corpus/*.md", "never_upload": ["questions.jsonl", "题库与标准答案.md", "sources_raw/", "articles.json", "metadata.json", "README.md"],
            "status": "gold dataset prepared and validated; no live RAG score has been measured"}
    (ROOT / "metadata.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    lines = ["# 企业制度 RAG 测试题库与标准答案", "", "固定版本：2026-11-01；44题，其中40题有依据、4题资料不足。",
             "", "问题根据财政部2010年公开发布的企业内控指引人工编制，不是生产用户日志。只按这套固定资料评分，不代表任何公司的现行制度。",
             "", "**不要将本文件或 questions.jsonl 上传知识库。只上传 corpus 目录中的10份 Markdown。**", "", "## 原始资料", "",
             "| 编号 | 资料 | 原PDF页码 | 条款数 |", "| --- | --- | --- | --- |"]
    for source in sources:
        pages = source["pdf_pages"]
        lines.append(f"| {source['source_id']} | [{source['title']}]({source['url']}#page={pages[0]}) | {pages[0]}–{pages[-1]} | {source['article_count']} |")
    lines.extend(["", "## 评分方法", "", "答案允许同义表达，必须覆盖必答要点并保留条件和例外；额外编造金额、期限或权限应判错误。检索命中和回答正确分开统计。跨文档题必须覆盖全部必需来源与证据。资料不足题不进入检索命中率分母，单独统计拒答正确率。", ""])
    for case in cases:
        lines += [f"## {case['id']} · {case['topic']} · {case['type']}", "", f"**问题：** {case['question']}", "",
                  f"**预期答案：** {case['expected_answer']}", "", "**必答要点：** " + "；".join(case["required_points"]), ""]
        if case["answerable"]:
            lines += ["**依据（以下证据均需覆盖）：**", ""]
            for evidence in case["evidence"]:
                pages = "、".join(map(str, evidence["pdf_pages"]))
                lines += [f"- {evidence['source_id']} {evidence['article']}，原 PDF 第{pages}页：[官方原文]({evidence['url']})。", f"  > {evidence['quote']}", ""]
        else:
            lines += [f"**拒答依据：** {case['absence_reason']}。判断范围为全部10份测试资料，不可从常识或其他公司的制度猜测。", ""]
    (ROOT / "题库与标准答案.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    with zipfile.ZipFile(ROOT / "仅上传知识库_10份制度资料.zip", "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for source in sources:
            archive.write(ROOT / source["path"], arcname=source["filename"])
    return meta


